"""Writes a unitree_mujoco scene with the B2 standing guard in the RIGSA hallway building.

ros2 run rigsa_alpha make_unitree_scene ~/unitree_mujoco/unitree_robots/b2/scene_rigsa.xml
then:  ./unitree_mujoco -r b2 -s scene_rigsa.xml -i 1 -n lo

The B2 starts at the simulator's world origin facing +x, so the building is shifted so that the origin is the
sentry post scenario.SENTRY_POST in the map. b2_bridge uses the same post to put the B2 back in map coordinates.
"""
import sys

from rigsa_alpha.floor import FURNITURE, WALLS
from rigsa_alpha.mujoco_world import building_geoms
from rigsa_alpha.scenario import SENTRY_POST

TEMPLATE = '''<mujoco model="b2 rigsa hallway">
  <!-- Generated by: ros2 run rigsa_alpha make_unitree_scene. The B2 stands at the sentry post
       (map x={px}, y={py}) facing down the hallway towards the entrance. -->
  <include file="b2.xml"/>

  <statistic center="0 0 0.5" extent="3"/>

  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <rgba haze="0.15 0.25 0.35 1"/>
    <global azimuth="160" elevation="-30"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.3 0.5 0.7" rgb2="0 0 0" width="512" height="3072"/>
    <texture type="2d" name="groundplane" builtin="checker" mark="edge" rgb1="0.2 0.3 0.4" rgb2="0.1 0.2 0.3"
      markrgb="0.8 0.8 0.8" width="300" height="300"/>
    <material name="groundplane" texture="groundplane" texuniform="true" texrepeat="5 5" reflectance="0.2"/>
  </asset>

  <worldbody>
    <light pos="0 0 6" dir="0 0 -1" directional="true"/>
    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane"/>
    {geoms}
  </worldbody>
</mujoco>
'''


def scene_xml():
    px, py, pyaw = SENTRY_POST
    if pyaw != 0.0:
        raise SystemExit('make_unitree_scene only shifts the building; keep the SENTRY_POST yaw at 0')
    return TEMPLATE.format(px=px, py=py, pyaw=pyaw,
                           geoms='\n    '.join(building_geoms(WALLS, FURNITURE, dx=-px, dy=-py)))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith('--') else None
    xml = scene_xml()
    if out:
        with open(out, 'w') as f:
            f.write(xml)
        print('wrote', out)
    else:
        print(xml)


if __name__ == '__main__':
    main()
